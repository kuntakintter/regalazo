interface HubSeed {
  topic: string;
  breadcrumb: string;
  eyebrow: string;
  sub: string;
  kw: string[];
}

function makeHubs(
  langMeta: {
    brand: string;
    titleTpl: (topic: string) => string;
    socialTpl: (topic: string) => string;
    descTpl: (topic: string, sub: string) => string;
    h1Tpl: (topic: string) => string;
  },
  seeds: Record<string, HubSeed>
): Record<string, HubCopy> {
  const out: Record<string, HubCopy> = {};
  for (const [slug, s] of Object.entries(seeds)) {
    out[slug] = {
      title: langMeta.titleTpl(s.topic),
      socialTitle: langMeta.socialTpl(s.topic),
      description: langMeta.descTpl(s.topic, s.sub),
      eyebrow: s.eyebrow,
      h1: langMeta.h1Tpl(s.topic),
      subtitle: s.sub,
      breadcrumbLabel: s.breadcrumb,
      keywords: s.kw,
    };
  }
  return out;
}

